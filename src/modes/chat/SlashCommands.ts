/**
 * Парсит слэш-команду в начале текста.
 * Возвращает null, если текст не начинается со слэш-команды.
 *
 * @param text — исходный текст сообщения
 */
export function parseSlashCommand(text: string): SlashParseResult | null {
  const match = text.match(/^\/(\S+)\s*(.*)/);
  if (!match) return null;
  return { name: match[1], argument: (match[2] || '').trim() };
}

/**
 * Ищет встроенную команду по имени.
 *
 * @param name — имя команды без "/"
 */
export function getSlashCommand(name: string): SlashCommand | undefined {
  return SLASH_COMMANDS.find((c) => c.name === name);
}
