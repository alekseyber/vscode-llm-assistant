// Каждая команда инжектирует system-промпт с директивной инструкцией.
// Работает в режимах chat + agent, НЕ в Plan Mode.
// Чистый модуль без зависимостей от vscode — легко тестируется.

/** Определение одной слэш-команды */
export interface SlashCommand {
  /** Имя команды без "/" (например "explain") */
  name: string;
  /** Краткое описание назначения (для документации) */
  description: string;
  /** Задача по умолчанию — подставляется в текст, если аргумент пуст */
  defaultTask: string;
  /** Директивный system-промпт, инжектируется в messages на позицию 1 */
  promptTemplate: string;
}

/** Результат парсинга префикса слэш-команды */
export interface SlashParseResult {
  /** Имя команды без "/" */
  name: string;
  /** Текст после имени команды (задача), может быть пустым */
  argument: string;
}

